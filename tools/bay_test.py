#!/usr/bin/env python3
"""WSKR orders: manual control with link range, search pattern, relay, depth, formation, gating, save/load.  python3 tools/wskr_orders_test.py"""
import os, sys, importlib.util
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("smoke", os.path.join(ROOT, "tools", "smoke.py"))
smoke = importlib.util.module_from_spec(spec); spec.loader.exec_module(smoke)
SHOTS = os.path.join(ROOT, "tools", "shots")
fails = []
def check(name, ok, extra=""):
    print(("ok   " if ok else "FAIL ") + name + (f"  {extra}" if extra and not ok else ""))
    if not ok: fails.append(name)
def main():
    server, site = smoke.start_server()
    for gated in (False,):
        base = f"http://127.0.0.1:{server.server_address[1]}/AquaNova/tablet/{'?locked=1' if gated else ''}"
        with sync_playwright() as p:
            browser = smoke.launch(p)
            page = browser.new_context(viewport={"width": 1180, "height": 820}, has_touch=True).new_page(); errors = []
            page.on("pageerror", lambda e: errors.append(str(e)[:200]))
            page.on("console", lambda m: errors.append(m.text[:200]) if m.type == "error" else None)
            js = lambda code: page.evaluate("(async()=>{const sim=(await import('./js/sim.js')).sim;const T=await import('./js/sim.js');" + code + "})()")
            page.goto(base); page.wait_for_function("!document.getElementById('board-btn').disabled", timeout=20000)
            page.tap("#board-btn"); page.wait_for_timeout(800)
            page.evaluate("import('./js/sim.js').then(m=>m.setTimeScale(30))"); page.wait_for_timeout(200)   # these tests were written for the old 30x pace
            if page.is_visible(".modal .btn"): page.tap(".modal .btn"); page.wait_for_timeout(300)
            page.evaluate("import('./js/sim.js').then(m=>m.setTimeScale(120))"); page.wait_for_timeout(200)
            B = "const B=await import('./js/bayops.js');"
            js("const s=sim.s; const c=sim.dockPoi(); Object.assign(s,{lat:c.lat+0.07,lon:c.lon,wskrs:[],rov:null,docked:false,wpt:null,speed:0,throttle:0,depth:0,targetDepth:0,heading:0,at:null}); s.rack={}; s.bay={op:null,doorDmg:0}; s.shuttle={state:'bay',bat:100,mode:'follow'}; return 1")
            r = js("sim.deployWskr(); const w=sim.s.wskrs[0]; w.mode='escort'; w.moving=false; const m=T.wskrMinutes(w); sim.s.wskrs=[]; return m.empty")
            check("WSKR battery lasts 6 h holding station (about 450 min at draw 0.8)", 430 < r < 470, str(r))
            r = js(B + "return B.launchWskr()")
            check("a launch starts a timed bay operation", r["ok"] and r["secs"] >= 59, str(r))
            check("WSKR is not out until the minute is up", js("return sim.s.wskrs.length") == 0)
            page.wait_for_timeout(1500)
            check("then it is launched", js("return sim.s.wskrs.length") == 1, str(js("return sim.s.bay.op")))
            # recall and recharge
            js("const w=sim.s.wskrs[0]; w.bat=40; w.mode='recall'; w.lat=sim.s.lat+0.01; return 1"); page.wait_for_timeout(2500)
            r = js("const w=sim.s.wskrs[0]; return {arr: w && w.arrived, op: sim.s.bay.op && sim.s.bay.op.kind, n: sim.s.wskrs.length}")
            check("recalled WSKR comes alongside and the bay takes it aboard", r["arr"] or r["op"] == "recover" or r["n"] == 0, str(r))
            page.wait_for_timeout(2500)
            r = js("return {n: sim.s.wskrs.length, rack: sim.s.rack[1]}")
            check("WSKR is racked with its charge, charging", r["n"] == 0 and r["rack"] is not None and 40 <= r["rack"] <= 100, str(r))
            page.wait_for_timeout(1500)
            r2 = js("return sim.s.rack[1]")
            check("charging raises the rack battery (2 h full: 100% in 7200 game s)", r2 > r["rack"], str((r, r2)))
            js("sim.s.rack[2]=10; return 1")
            r = js(B + "return B.launchWskr(2)")
            check("a WSKR below 20% charge cannot launch", not r["ok"] and r["why"] == "charge", str(r))
            # speed rules
            js("sim.s.rack={}; sim.s.bay={op:null,doorDmg:0,override:true}; sim.s.damage=0; return 1")
            r = js(B + "const s=sim.s; s.speed=15; s.throttle=1; const d0=s.damage; B.launchWskr(); return {d0}"); page.wait_for_timeout(1000)
            r = js("const s=sim.s, b=s.bay; return {kt:s.speed, dmg:s.damage, door:b.doorDmg}")
            check("bay open above 8 kt damages the ship", r["kt"] > 8 and r["dmg"] > 0, str(r))
            check("bay open above 10 kt damages the doors for good", r["kt"] > 10 and r["door"] > 0, str(r))
            js("const s=sim.s; s.throttle=0; s.speed=0; s.damage=0; s.bay={op:null,doorDmg:0}; s.wskrs=[]; return 1"); page.wait_for_timeout(1500)
            r = js(B + "const d0=sim.s.damage; B.launchWskr(); return d0")
            page.wait_for_timeout(1500)
            check("slow launch is free", js("return sim.s.damage") == 0 and js("return sim.s.bay.doorDmg") == 0)
            js("sim.s.wskrs=[]; sim.s.bay.op=null; return 1")
            # shuttle
            js("const s=sim.s; Object.assign(s,{speed:0,throttle:0}); return 1")
            check("shuttle needs a pilot", js(B + "B.setManning(0,0); const r=B.launchShuttle(); B.setManning(2,2); return r.why") == "pilot")
            r = js(B + "return B.launchShuttle()")
            check("shuttle launch takes a minute", r["ok"] and r["secs"] >= 59, str(r))
            page.wait_for_timeout(1500)
            check("shuttle is out", js("return sim.s.shuttle.state") == "out", str(js("return sim.s.shuttle")))
            r = js(B + "const p=sim.dockPoi(); const x=B.sendShuttle(p, true); return {ok:x.ok, mode:sim.s.shuttle.mode, nm:x.nm}")
            check("shuttle sent to the dock with a team", r["ok"] and r["mode"] == "going", str(r))
            seen = set()
            for _ in range(40):
                page.wait_for_timeout(500); seen.add(js("return sim.s.shuttle.mode"))
                if "moored" in seen: break
            check("it arrives, cycles the airlock and moors with the team ashore", "exchange" in seen or "moored" in seen, str(seen))
            r = js("const sh=sim.s.shuttle; return {mode:sh.mode, pax:sh.pax, ashore:sh.ashore}")
            check("away team is ashore", r["mode"] == "moored" and r["pax"] == 0 and r["ashore"] == 2, str(r))
            js(B + "B.recallShuttle(); return 1")
            for _ in range(60):
                page.wait_for_timeout(500)
                if js("return sim.s.shuttle.mode") == "follow": break
            r = js("const sh=sim.s.shuttle; return {mode:sh.mode, pax:sh.pax, bat:sh.bat}")
            check("team boards and the shuttle is back alongside the ship", r["mode"] == "follow" and r["pax"] == 2, str(r))
            r = js(B + "return B.recoverShuttle()")
            check("shuttle can be taken aboard (1 min + 10 s airlock)", r["ok"] and r["secs"] >= 69, str(r))
            page.wait_for_timeout(2500)
            r = js("const sh=sim.s.shuttle; return {st:sh.state, bat:sh.bat}")
            check("shuttle is aboard", r["st"] == "bay", str(r))
            b0 = r["bat"]; page.wait_for_timeout(1500)
            check("shuttle charges in the bay", b0 >= 100 or js("return sim.s.shuttle.bat") > b0, str(b0))
            # shuttle battery and air research, air supply
            RES = lambda ids: js("const g=(await import('./js/persist.js')).gameState; const s=g.getProperty('mission.science')||{}; g.updateProperty('mission.science',{...s,done:" + str(ids) + "}); return 1")
            RES([])
            check("shuttle battery starts at 1 h, air at 7 h", js(B + "return [B.shuttleHours(), B.shuttleO2Hours()]") == [1, 7])
            RES(["shuttle-battery-3"]); check("long-life cells make it 3 h", js(B + "return B.shuttleHours()") == 3)
            RES(["shuttle-battery-3", "shuttle-battery-6", "shuttle-o2"]); check("deep-cycle cells 6 h, scrubbers 9 h of air", js(B + "return [B.shuttleHours(), B.shuttleO2Hours()]") == [6, 9])
            RES([])
            js("const s=sim.s; s.docked=false; s.autoAvoid=false; s.lat=39.0; s.lon=-68.0; s.at=null; s.depth=200; s.targetDepth=200; Object.assign(s.shuttle,{state:'out',mode:'follow',lat:s.lat,lon:s.lon,pilots:2,pax:6,o2:100,bat:100,dead:false}); return 1")
            js("for(let i=0;i<100;i++) sim.step(0.1); return 1")
            r = js("return 100-sim.s.shuttle.o2"); check("air falls about 4% in 20 game min with 8 aboard (7 h)", 3.4 < r < 5, str(r))
            js("const sh=sim.s.shuttle; Object.assign(sh,{pilots:1,pax:0,o2:100}); for(let i=0;i<100;i++) sim.step(0.1); return 1")
            r1 = js("return 100-sim.s.shuttle.o2"); check("one pilot alone breathes an eighth as fast", r1 < r / 4, str((r, r1)))
            RES(["shuttle-o2"]); js("const sh=sim.s.shuttle; Object.assign(sh,{pilots:2,pax:6,o2:100}); for(let i=0;i<100;i++) sim.step(0.1); return 1")
            r2 = js("return 100-sim.s.shuttle.o2"); check("scrubbers slow it (9 h)", r2 < r * 0.9, str((r, r2))); RES([])
            RES(["shuttle-battery-3", "shuttle-battery-6"]); check("range is held down by the air when full of people", js(B + "const sh=sim.s.shuttle; Object.assign(sh,{pilots:2,pax:6,o2:40,bat:100}); return B.shuttleRangeNm()") < js(B + "const sh=sim.s.shuttle; Object.assign(sh,{pilots:1,pax:0,o2:40,bat:100}); return B.shuttleRangeNm()")); RES([])
            js("const sh=sim.s.shuttle; Object.assign(sh,{state:'out',pilots:2,pax:6,o2:14,bat:100,mode:'going',dest:sim.dockPoi(),dead:false,moving:false}); sim.s.shuttle.lat=sim.s.lat+0.2; return 1"); js("for(let i=0;i<5;i++) sim.step(0.1); return 1")
            check("low air turns her back", js("return sim.s.shuttle.mode") == "returning")
            js("const sh=sim.s.shuttle; Object.assign(sh,{o2:0.01,mode:'follow',pilots:2,pax:6}); for(let i=0;i<30;i++) sim.step(0.1); return 1")
            check("no air leaves her adrift", js("return sim.s.shuttle.dead") is True)
            js("const sh=sim.s.shuttle; Object.assign(sh,{state:'bay',mode:'follow',dead:false,o2:0,bat:100,pilots:2,pax:0}); for(let i=0;i<100;i++) sim.step(0.1); return 1")
            r = js("return sim.s.shuttle.o2"); check("air refills in the bay in 1 h (about 33% in 20 game min)", 30 < r < 37, str(r))
            check("a shuttle with thin air will not launch", js(B + "Object.assign(sim.s.shuttle,{o2:10,bat:100}); return B.launchShuttle().why") == "o2")
            js("Object.assign(sim.s.shuttle,{o2:100,bat:100,state:'bay',mode:'follow',dead:false,pilots:2,pax:0}); return 1")
            # Remora through the bay: doors stay open on the tether, other craft are blocked, then unload and re-equip
            js("const s=sim.s; Object.assign(s,{speed:0,throttle:0,rov:null,wskrs:[],damage:0}); s.bay={op:null,doorDmg:0,base:0,rearm:null}; s.rack={}; return 1")
            r = js(B + "return B.launchRemora()"); check("Remora launch is a timed bay operation", r["ok"] and r["secs"] >= 59, str(r))
            check("Remora is not out until the minute is up", js("return !!sim.s.rov") is False)
            page.wait_for_timeout(1500)
            check("then she is out", js("return !!sim.s.rov") is True)
            r = js(B + "return [B.launchWskr().why, B.launchShuttle().why]"); check("her tether blocks WSKR and shuttle launches", r == ["tether", "tether"], str(r))
            js("window.__ev=[]; sim.on((t,d)=>window.__ev.push(t)); const s=sim.s; s.bay.override=true; s.speed=12; s.throttle=1; return 1"); page.wait_for_timeout(800)
            r = js("const s=sim.s; return {door:s.bay.doorDmg, dmg:s.damage}"); check("doors open for the tether: speed over 10 kt damages them with no operation running", r["door"] > 0 and r["dmg"] > 0, str(r))
            ev = page.evaluate("window.__ev"); check("Engineering is told (bay-warn, bay-door-damage)", "bay-warn" in ev and "bay-door-damage" in ev, str(ev))
            js("const s=sim.s; s.throttle=0; s.speed=0; s.bay.doorDmg=0; return 1"); page.wait_for_timeout(400)
            js("const m=await import('./js/science.js'); m.addSample('water',null,'bottle'); return 1") if False else None
            js("const s=sim.s; s.rov.lat=s.lat; s.rov.lon=s.lon; s.rov.cargo=[{kind:'water',site:null,tool:'collector'}]; window.__lab0=(await import('./js/science.js')).samples().length; return 1")
            r = js(B + "return B.recoverRemora()"); check("Remora recovery is a timed operation too", r["ok"] and r["secs"] >= 59, str(r))
            page.wait_for_timeout(1500)
            r = js("const s=sim.s; return {rov:!!s.rov, rearm:s.bay.rearm}"); check("aboard: the team unload and re-equip (5 min at least)", r["rov"] is False and r["rearm"] and r["rearm"]["dur"] >= 300, str(r))
            r = js("const m=await import('./js/science.js'); return {held: s=sim.s.bay.rearm ? sim.s.bay.rearm.cargo.length : 0, lab: m.samples().length-window.__lab0}"); check("the sample is still in the ROV, not the lab, until unloaded", r["held"] == 1 and r["lab"] == 0, str(r))
            r = js(B + "return B.launchRemora()"); check("she cannot launch until she is re-equipped", not r["ok"] and r["why"] == "rearm", str(r))
            page.wait_for_timeout(4000)
            check("then she is ready again", js("return sim.s.bay.rearm") is None and js(B + "return B.launchRemora().ok") is True)
            check("the unloaded sample reached the lab", js("return (await import('./js/science.js')).samples().length-window.__lab0") == 1)
            page.wait_for_timeout(1500); js("sim.s.rov=null; sim.s.bay.op=null; return 1")
            # UI
            js("window.__aq.open('bay'); return 1"); page.wait_for_timeout(700)
            t = page.inner_text("#station").lower()
            check("bay page shows doors, WSKRs, shuttle", "bay doors" in t and "tern" in t and "wskr 1" in t and "pilots" in t and "passengers" in t, t[:300])
            check("no page errors", not errors, str(errors[:2]))
            browser.close()
    server.shutdown()
    sys.exit(1 if fails else 0)
main()
