#!/usr/bin/env python3
"""New game: arrival form in Walkway AN-1, ID record, PED on the bed, pin on the desk, the name in the game.  python3 tools/intake_test.py"""
import os, sys, importlib.util
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("smoke", os.path.join(ROOT, "tools", "smoke.py"))
smoke = importlib.util.module_from_spec(spec); spec.loader.exec_module(smoke)
SHOTS = os.path.join(ROOT, "tools", "shots")
fails = []
def check(name, ok, extra=""):
    print(("ok   " if ok else "FAIL ") + name + (f"  {extra}" if extra and not ok else ""))
    if not ok: fails.append(name)
def main():
    server, site = smoke.start_server()
    base = f"http://127.0.0.1:{server.server_address[1]}/AquaNova/tablet/?intake=1"
    with sync_playwright() as p:
        browser = smoke.launch(p)
        page = browser.new_context(viewport={"width": 1180, "height": 820}, has_touch=True).new_page(); errors = []
        page.on("pageerror", lambda e: errors.append(str(e)[:200]))
        page.on("console", lambda m: errors.append(m.text[:200]) if m.type == "error" else None)
        page.goto(base); page.wait_for_function("!document.getElementById('board-btn').disabled", timeout=20000)
        page.tap("#board-btn"); page.wait_for_timeout(900)
        js = lambda code: page.evaluate("(async()=>{const g=(await import('./js/persist.js')).gameState;" + code + "})()")
        check("starts in walkway AN-1 with the form", page.is_visible(".signin") and page.is_visible(".scene.walkway2:not([hidden])") or page.is_visible(".signin"))
        check("PED button hidden before the PED is collected", not page.is_visible("#ped-btn"))
        page.screenshot(path=f"{SHOTS}/i-1form.png")
        check("scanner starts disabled", page.locator(".scanner").is_disabled())
        page.fill("#f-first", "alex"); page.fill("#f-last", "o'neil-ray")
        check("scanner still disabled without the declaration", page.locator(".scanner").is_disabled())
        page.locator(".f-tick input").check()
        check("scanner enabled when the form is complete", not page.locator(".scanner").is_disabled())
        page.fill("#f-last", "x1"); check("a name with digits is refused", page.locator(".scanner").is_disabled() and "letters" in page.inner_text(".f-msg"))
        page.fill("#f-last", "o'neil-ray")
        page.tap(".scanner", force=True); page.wait_for_timeout(500)
        check("scanning animation runs", page.locator(".scanner.scanning").count() == 1)
        page.screenshot(path=f"{SHOTS}/i-2scan.png")
        page.wait_for_timeout(2600)
        t = page.inner_text(".signin")
        check("ID record shows the name, rank and clearance", "Alex O'Neil-Ray" in t and "Captain" in t and "Omega" in t and "BIOMETRIC IDENTIFICATION CONFIRMED" in t.upper(), t[:300])
        check("record tells the player to report to quarters", "report to your Quarters immediately" in t and "message from O.E.R.A. Operations" in t)
        page.screenshot(path=f"{SHOTS}/i-3record.png")
        check("name saved", js("return JSON.stringify(g.getProperty('progress.player'))") == '{"first":"Alex","surname":"O\'Neil-Ray","name":"Alex O\'Neil-Ray","rank":"Captain"}')
        page.tap(".signin .btn.primary"); page.wait_for_timeout(500)
        check("form closed", not page.is_visible(".signin"))
        check("the way to quarters glows", page.locator('.hs[aria-label="A1 DECK ▼"].glow').count() == 1)
        page.evaluate("window.__aq.scene('walkway')"); page.wait_for_timeout(400)
        check("quarters door glows on the walkway", page.locator('.door[aria-label="QUARTERS"].glow').count() == 1)
        page.screenshot(path=f"{SHOTS}/i-4walkway.png")
        page.evaluate("window.__aq.scene('quarters')"); page.wait_for_timeout(600)
        check("PED lies on the bed and the pin on the desk", page.is_visible('.pickup[aria-label="Pick up PED"]') and page.is_visible('.pickup[aria-label="Pick up communicator"]'))
        check("laptop glows", page.locator('.hs[aria-label="LOGBOOK"].glow').count() == 1)
        page.screenshot(path=f"{SHOTS}/i-5quarters.png")
        # PED first, then the logbook, then the pin
        page.locator('.pickup[aria-label="Pick up PED"]').tap(force=True); page.wait_for_timeout(500)
        check("PED collected, button appears, item gone", page.is_visible("#ped-btn") and not page.is_visible('.pickup[aria-label="Pick up PED"]'))
        page.tap('.hs[aria-label="LOGBOOK"]', force=True); page.wait_for_timeout(600)
        t = page.inner_text("#station")
        check("logbook greets the captain by name", "Captain O'Neil-Ray," in t and "Admiral Elena Vasquez" in t and "{captain}" not in t, t[:200])
        done = page.evaluate("[...document.querySelectorAll('#station .entry li.done')].map(x=>x.textContent)")
        check("PED task is ticked, pin task is not", "Collect your PED from the bed" in done and "Collect your communicator pin from the desk" not in done, done)
        page.screenshot(path=f"{SHOTS}/i-6log.png")
        page.evaluate("document.querySelector('#station .st-head .btn').click()"); page.wait_for_timeout(300)
        check("laptop stops glowing after reading", page.locator('.hs[aria-label="LOGBOOK"].glow').count() == 0)
        page.locator('.pickup[aria-label="Pick up communicator"]').tap(force=True); page.wait_for_timeout(600)
        check("pin collected, pin visible in the corner", page.is_visible("#pin"))
        page.evaluate("document.querySelector('.modal-back .btn') && document.querySelector('.modal-back .btn').click()"); page.wait_for_timeout(300)
        page.tap("#ped-btn"); page.wait_for_timeout(600)
        page.evaluate("[...document.querySelectorAll('#ped-pop .pda-screen button, #ped-pop .pda-screen .tab')].find(b=>/contacts/i.test(b.textContent)).click()"); page.wait_for_timeout(400)
        t = page.inner_text("#ped-pop")
        check("contacts list the player with bio and first name", "Captain Alex O'Neil-Ray" in t and "call you Alex" in t, t[:300])
        page.screenshot(path=f"{SHOTS}/i-7contacts.png")
        # reload: name and items persist, the form does not come back
        page.goto(base); page.wait_for_function("!document.getElementById('board-btn').disabled", timeout=20000)
        page.tap("#board-btn"); page.wait_for_timeout(900)
        check("after reload no form, name kept", not page.is_visible(".signin") and js("return g.getProperty('progress.player').surname") == "O'Neil-Ray")
        check("no page errors", not errors, errors[:3])
        browser.close()
    print("\n%d failure(s)" % len(fails)); sys.exit(1 if fails else 0)
main()
