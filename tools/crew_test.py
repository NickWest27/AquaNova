#!/usr/bin/env python3
"""Communicator orders: working orders act, unfinished ones are marked.  python3 tools/crew_test.py"""
import os, sys, importlib.util
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("smoke", os.path.join(ROOT, "tools", "smoke.py"))
smoke = importlib.util.module_from_spec(spec); spec.loader.exec_module(smoke)
fails = []
def check(name, ok, extra=""):
    print(("ok   " if ok else "FAIL ") + name + (f"  {extra}" if extra and not ok else ""))
    if not ok: fails.append(name)
def main():
    server, site = smoke.start_server()
    base = f"http://127.0.0.1:{server.server_address[1]}/AquaNova/tablet/"
    with sync_playwright() as p:
        browser = smoke.launch(p)
        ctx = browser.new_context(viewport={"width": 1180, "height": 820}, has_touch=True)
        page = ctx.new_page(); errors = []
        page.on("pageerror", lambda e: errors.append(str(e)[:200]))
        js = lambda code: page.evaluate("(async()=>{const sim=(await import('./js/sim.js')).sim;const g=(await import('./js/persist.js')).gameState;" + code + "})()")
        page.goto(base); page.wait_for_function("!document.getElementById('board-btn').disabled", timeout=20000)
        page.tap("#board-btn"); page.wait_for_timeout(800)
        if page.is_visible(".modal .btn"): page.tap(".modal .btn"); page.wait_for_timeout(300)
        js("const m=(await import('../game/systems/missionManager.js')).default; m.forceCompleteMission('meetTheCrew'); sim.s.docked=false; sim.s.speed=0; sim.s.lat=39.45; sim.s.lon=-72.25; sim.s.at=null; g.updateProperty('contacts.crew.engineering.known', true)")
        page.evaluate("window.__aq.scene('bridge')"); page.wait_for_timeout(300)
        page.evaluate("document.querySelector('#pin').click()")
        page.wait_for_timeout(700)
        say = lambda t: (page.fill(".comm-input", t), page.press(".comm-input", "Enter"), page.wait_for_timeout(300))
        check("single tap opens it quiet (typing)", "quiet" in page.inner_text(".comm-top").lower() and "Type to the crew" in page.get_attribute(".comm-input", "placeholder"))
        page.mouse.click(8, 8); page.wait_for_timeout(400)
        box = page.locator("#pin").bounding_box(); page.mouse.move(box["x"] + 20, box["y"] + 20); page.mouse.down(); page.wait_for_timeout(700); page.mouse.up(); page.wait_for_timeout(600)
        check("press and hold opens the voice channel", page.is_visible("#comm-pop .comm-page") and "voice" in page.inner_text(".comm-top").lower(), page.inner_text(".comm-top") if page.is_visible(".comm-top") else "closed")
        check("a hold does not also close it", page.is_visible("#comm-pop .comm-page"))
        check("no buttons in the communicator", page.locator("#comm-pop button").count() == 0, page.locator("#comm-pop button").count())
        check("one line to speak or type", page.locator("#comm-pop .comm-input").count() == 1)
        say("Helm, make your depth one hundred metres")
        check("spoken depth order sets target depth", js("return sim.s.targetDepth") == 100, js("return sim.s.targetDepth"))
        check("Marcus answers", "marcus" in page.inner_text(".comm-log").lower(), page.inner_text(".comm-log"))
        h0 = js("return sim.s.targetHeading"); say("Come right forty five")
        h1 = js("return sim.s.targetHeading"); check("come right 45 turns the ship", round((h1 - h0) % 360) == 45, (h0, h1))
        say("Helm, make your heading two seven zero".replace("two seven zero", "270"))
        check("heading order", abs(js("return sim.s.targetHeading") - 270) < 1, js("return sim.s.targetHeading"))
        say("speed sixty percent")
        check("speed order sets throttle", abs(js("return sim.s.throttle") - 0.6) < 0.01, js("return sim.s.throttle"))
        say("ARIA, status report")
        check("ARIA gives a status report", "Battery" in page.inner_text(".comm-log"), page.inner_text(".comm-log"))
        say("Engineering, make your depth 50 metres")
        check("wrong officer redirects", "matter for" in page.inner_text(".comm-log"), page.inner_text(".comm-log"))
        say("blah blah")
        check("unknown speech asks again", "Say again" in page.inner_text(".comm-log"))
        # a table of phrases the parser must understand (and what it must route to)
        tbl = page.evaluate("""(async()=>{const m=await import('./js/stations/crew.js'); const out={}; for (const p of ['helm dive to three hundred meters','come left','turn right 20','steer north','all stop','undock please','take us home','prepare to dive','deploy the sensor buoys','hello aria','that is all','one hundred and twenty']) { const n=m.normalize(p); const u=m.understand(n); out[p]=u?(u.dept||u.kind):null; out['n:'+p]=n; } return out;})()""")
        check("parser routes depth to helm", tbl["helm dive to three hundred meters"] == "helm" and "300" in tbl["n:helm dive to three hundred meters"], tbl)
        check("parser: left, right, north, stop, undock", all(tbl[k] == "helm" for k in ["come left", "turn right 20", "steer north", "all stop", "undock please"]), tbl)
        check("parser: home, prepare, buoys", tbl["take us home"] == "executiveOfficer" and tbl["prepare to dive"] == "engineering" and tbl["deploy the sensor buoys"] == "sensors", tbl)
        check("parser: pleasantry, close, numbers", tbl["hello aria"] == "pleasantry" and tbl["that is all"] == "close" and tbl["n:one hundred and twenty"] == "120", tbl)
        js("sim.s.docked=true; sim.s.at=sim.dockPoi(); sim.s.speed=0")
        say("Helm, undock"); page.wait_for_timeout(5500)
        check("Undock order undocks the ship", js("return sim.s.docked") is False)
        page.screenshot(path=os.path.join(ROOT, "tools", "shots", "crew_reply.png"))
        check("no page errors", not errors, errors)
        browser.close()
    server.shutdown()
    print("\nFAILED: " + ", ".join(fails) if fails else "\nAll checks passed.")
    sys.exit(1 if fails else 0)
main()
