def build(out):
    order = [' '] + sorted(G)
    names = {c: ('space' if c == ' ' else 'uni%04X' % ord(c)) for c in order}
    fb = FontBuilder(16, isTTF=True); fb.setupGlyphOrder(['.notdef'] + [names[c] for c in order])
    fb.setupCharacterMap({ord(c): names[c] for c in order})
    def glyph(rows, first):
        pen = TTGlyphPen(None)
        for ri, row in enumerate(rows):
            r = first + ri; y = (6 - r) * 2   # row 6 sits on the baseline
            x = 0
            while x < 5:
                if row[x] == '#':
                    x0 = x
                    while x < 5 and row[x] == '#': x += 1
                    pen.moveTo((x0 * 2, y)); pen.lineTo((x0 * 2, y + 2)); pen.lineTo((x * 2, y + 2)); pen.lineTo((x * 2, y)); pen.closePath()
                else: x += 1
        return pen.glyph()
    gl = {'.notdef': TTGlyphPen(None).glyph()}
    for c in order:
        gl[names[c]] = TTGlyphPen(None).glyph() if c == ' ' else glyph([r.ljust(5, '.') for r in G[c][1].split('/')], G[c][0])
    fb.setupGlyf(gl)
    fb.setupHorizontalMetrics({n: (12, 0) for n in ['.notdef'] + [names[c] for c in order]})
    fb.setupHorizontalHeader(ascent=14, descent=-2); fb.setupNameTable({'familyName': 'AQ Pixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=14, sTypoDescender=-2, usWinAscent=14, usWinDescent=2); fb.setupPost(); fb.save(out)
