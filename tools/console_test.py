#!/usr/bin/env python3
"""Bridge console: top display, main screen, left selector, center controls, right data.  python3 tools/console_test.py"""
import re, os, sys, importlib.util
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("smoke", os.path.join(ROOT, "tools", "smoke.py"))
smoke = importlib.util.module_from_spec(spec); spec.loader.exec_module(smoke)
fails = []
def check(name, ok, extra=""):
    print(("ok   " if ok else "FAIL ") + name + (f"  {extra}" if extra and not ok else ""))
    if not ok: fails.append(name)
def main():
    server, site = smoke.start_server()
    base = f"http://127.0.0.1:{server.server_address[1]}/AquaNova/tablet/"
    with sync_playwright() as p:
        browser = smoke.launch(p)
        ctx = browser.new_context(viewport={"width": 1180, "height": 820}, has_touch=True)
        page = ctx.new_page(); errors = []
        page.on("pageerror", lambda e: errors.append(str(e)[:200]))
        page.goto(base); page.wait_for_function("!document.getElementById('board-btn').disabled", timeout=20000)
        page.tap("#board-btn"); page.wait_for_timeout(800)
        if page.is_visible(".modal .btn"): page.tap(".modal .btn"); page.wait_for_timeout(300)
        page.wait_for_timeout(800); print("ERR", errors); page.evaluate("window.__aq.scene('bridge')"); page.wait_for_timeout(1200)
        top = page.inner_text(".bt")
        check("top display shows lat/long and date", "°" in top and re.search(r"20\d\d", top), top)
        check("main screen defaults to navigation", page.is_visible(".bmain .bd-nav") and page.is_visible(".bdisp .bd-nav"))
        check("position log shown", "POSITION LOG" in page.inner_text(".nav-log"))
        check("nav readouts shown", "SPEED" in page.inner_text(".nav-read"))
        check("place name has its own line", page.is_visible(".bmain .nl-place"))
        check("profile drawn on the right", page.is_visible(".bmain .nav-prof canvas") and page.evaluate("document.querySelector('.bmain .prof-canvas').getContext('2d').getImageData(10,10,1,1).data[3]") > 0)
        pos = page.evaluate("(() => { const q = (s) => document.querySelector(s).getBoundingClientRect(); const m = q('.bmain'), r = q('.bmain .nav-read'), l = q('.bmain .nav-log'), p = q('.bmain .nav-prof'); return { readTop: r.top - m.top < m.height / 2, logBottom: l.top - m.top > m.height / 2, profRight: p.left - m.left > m.width / 2, within: p.right <= m.right && l.right < p.left } })()")
        check("readouts top-left, log bottom-left, profile right", all(pos.values()), pos)
        page.locator('.selector .bbtn:text-is("SYS")').tap(); page.wait_for_timeout(300)
        lt = page.locator('.bc:visible .bbtn:text-is("Lights")'); was = "on" in lt.get_attribute("class").split(); lt.tap(); page.wait_for_timeout(200)
        check("Lights button keeps its label and flips fill", lt.inner_text() == "Lights" and ("on" in lt.get_attribute("class").split()) != was)
        page.locator('.selector .bbtn:text-is("NAV")').tap(); page.wait_for_timeout(200)
        page.screenshot(path=os.path.join(ROOT, "tools", "shots", "console_nav.png"))
        r0 = page.inner_text(".bc:visible .rng"); page.locator('.bc:visible .bbtn:text-is("+")').tap(); page.wait_for_timeout(200)
        r1 = page.inner_text(".bc:visible .rng")
        check("+ increases range on the console", float(r1.split()[0]) > float(r0.split()[0]), (r0, r1))
        for name, sel in (("HELM", ".bdisp .bd-helm"), ("SYS", ".bdisp .bd-sys"), ("VIEW", ".bdisp .bd.view"), ("NAV", ".bdisp .bd-nav")):
            page.locator(f'.selector .bbtn:text-is("{name}")').tap(); page.wait_for_timeout(300)
            check(f"{name} shows on the main screen", page.is_visible(sel))
            if name == "HELM": page.screenshot(path=os.path.join(ROOT, "tools", "shots", "console_helm.png"))
        # plot a course by typed lat/long (docked ships are refused, so undock first)
        page.evaluate("window.__aq.scene('bridge')")
        page.locator('.bc:visible .bbtn:text-is("Plot a course")').tap(); page.wait_for_timeout(300)
        page.fill("#pc-lat", "39.45"); page.fill("#pc-lon", "-72.25"); page.locator('.modal .btn:text-is("Plot course")').tap(); page.wait_for_timeout(200)
        check("docked ship refuses a course", page.is_visible(".modal .pc") and "docked" in page.inner_text(".pc-msg"), page.inner_text(".pc-msg"))
        page.locator('.modal .btn:text-is("Cancel")').tap(); page.wait_for_timeout(200)
        page.evaluate("import('/AquaNova/tablet/js/sim.js').then(m => { const s = m.sim.s; s.docked = false; s.lat = 39.4; s.lon = -72.2; s.depth = 30; s.targetDepth = 30; })"); page.wait_for_timeout(400)
        page.locator('.bc:visible .bbtn:text-is("Plot a course")').tap(); page.wait_for_timeout(300)
        check("plot dialog opens without a marker", page.is_visible(".modal .pc"))
        page.fill("#pc-lat", "39.45 N"); page.fill("#pc-lon", "72 15 W"); page.wait_for_timeout(150)
        check("dialog previews bearing and distance", "bearing" in page.inner_text(".pc-msg"), page.inner_text(".pc-msg"))
        page.locator('.modal .btn:text-is("Plot course")').tap(); page.wait_for_timeout(400)
        check("dialog closes and course is set", not page.is_visible(".modal .pc") and "Waypoint 1" in page.inner_text(".br:visible"), page.inner_text(".br:visible"))
        page.locator('.bc:visible .bbtn:text-is("Plot a course")').tap(); page.wait_for_timeout(300)
        page.fill("#pc-lat", "0"); page.fill("#pc-lon", "0"); page.locator('.modal .btn:text-is("Plot course")').tap(); page.wait_for_timeout(200)
        check("bad position is refused with a reason", page.is_visible(".modal .pc") and "outside" in page.inner_text(".pc-msg"), page.inner_text(".pc-msg"))
        page.locator('.modal .btn:text-is("Place / Bearing")').tap(); page.select_option("#pc-place", "ship"); page.fill("#pc-brg", "270"); page.fill("#pc-dist", "3")
        page.locator('.modal .btn:text-is("Plot course")').tap(); page.wait_for_timeout(300)
        check("place + bearing + distance plots", not page.is_visible(".modal .pc") and "Waypoint 2" in page.inner_text(".br:visible"))
        page.locator('.bc:visible .bbtn:text-is("Clear")').tap(); page.wait_for_timeout(200)
        page.locator('.selector .bbtn:text-is("HELM")').tap(); page.wait_for_timeout(300)
        page.locator('.bc:visible .bbtn:text-is("Faster")').tap(); page.wait_for_timeout(300)
        check("Faster raises throttle", "10%" in page.inner_text(".br:visible") or "%" in page.inner_text(".br:visible"))
        page.locator(".bdisp .bd-promote").tap(); page.wait_for_timeout(300)
        check("MAIN sends helm to the main screen", page.is_visible(".bmain .bd-helm"))
        page.locator(".bd-expand:visible").tap(); page.wait_for_timeout(700)
        check("expand opens the full station", page.is_visible("#station .st-head"))
        page.tap("#station .st-head .btn"); page.wait_for_timeout(400)
        check("selection kept after returning", page.is_visible(".bdisp .bd-helm"))
        check("no page errors", not errors, errors)
        browser.close()
    server.shutdown()
    print("\nFAILED: " + ", ".join(fails) if fails else "\nAll checks passed.")
    sys.exit(1 if fails else 0)
main()
