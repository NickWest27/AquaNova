import { parseCoord, parseBearing, resolveTarget, project } from '../tablet/js/plotmath.js';
let fails = 0;
const check = (name, ok, extra = '') => { console.log((ok ? 'ok   ' : 'FAIL ') + name + (ok ? '' : '  ' + extra)); if (!ok) fails++; };
const near = (a, b, e = 1e-3) => a != null && Math.abs(a - b) < e;
check('decimal lat', near(parseCoord('39.45', true), 39.45));
check('deg-min with hemisphere', near(parseCoord("40 15.5 N", true), 40.258333));
check('deg symbol west', near(parseCoord("72°12'W", false), -72.2));
check('negative decimal lon', near(parseCoord('-72.25', false), -72.25));
check('south lat negative', near(parseCoord('10 S', true), -10));
check('wrong hemisphere rejected', parseCoord('40 E', true) === null && parseCoord('72 N', false) === null);
check('lat over 90 rejected', parseCoord('91', true) === null);
check('junk rejected', parseCoord('abc', true) === null && parseCoord('', true) === null);
check('bearing ok', parseBearing('045') === 45 && parseBearing('360') === 0 && parseBearing('270°') === 270);
check('bearing bad', parseBearing('361') === null && parseBearing('x') === null && parseBearing('-5') === null);
const ship = { lat: 39.4, lon: -72.2 }, pois = [{ id: 3, name: 'Mystic Reef', lat: 39.5, lon: -72.1 }];
const env = { ship, pois, inside: (la, lo) => la > 38 && la < 42 && lo > -74 && lo < -70, floorAt: (la) => (la > 41 ? 3 : 200) };
let r = resolveTarget({ mode: 'latlon', lat: '39.45', lon: '-72.25' }, env);
check('lat/long accepted', r.ok && near(r.point.lat, 39.45), JSON.stringify(r));
check('outside map rejected', !resolveTarget({ mode: 'latlon', lat: '45', lon: '-72' }, env).ok);
check('shallow rejected', !resolveTarget({ mode: 'latlon', lat: '41.5', lon: '-72' }, env).ok);
r = resolveTarget({ mode: 'place', place: '3', bearing: '', distance: '' }, env);
check('place only goes to the place', r.ok && r.poi && r.poi.name === 'Mystic Reef');
r = resolveTarget({ mode: 'place', place: '3', bearing: '90', distance: '' }, env);
check('place + bearing uses 5 nm', r.ok && Math.abs((r.point.lon - -72.1) * 60 * Math.cos(39.5 * Math.PI / 180) - 5) < 0.01 && near(r.point.lat, 39.5, 1e-6), JSON.stringify(r));
r = resolveTarget({ mode: 'place', place: 'ship', bearing: '0', distance: '12' }, env);
check('ship + bearing + distance', r.ok && near(r.point.lat, 39.4 + 12 / 60) && near(r.point.lon, -72.2, 1e-6), JSON.stringify(r));
check('distance without bearing rejected', !resolveTarget({ mode: 'place', place: '3', bearing: '', distance: '4' }, env).ok);
check('ship alone rejected', !resolveTarget({ mode: 'place', place: 'ship', bearing: '', distance: '' }, env).ok);
check('bad distance rejected', !resolveTarget({ mode: 'place', place: '3', bearing: '10', distance: '-2' }, env).ok && !resolveTarget({ mode: 'place', place: '3', bearing: '10', distance: '5x' }, env).ok);
check('projected point off the map rejected', !resolveTarget({ mode: 'place', place: '3', bearing: '0', distance: '300' }, env).ok);
console.log(fails ? '\nFAILED' : '\nAll checks passed.'); process.exit(fails ? 1 : 0);
